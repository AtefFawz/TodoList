import { spawnSync } from "node:child_process";
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const platform = process.argv[2];
if (!["android", "ios"].includes(platform)) {
  console.error("Usage: node scripts/native-setup.mjs <android|ios>");
  process.exit(1);
}

const root = process.cwd();
const target = resolve(root, platform);
const executable = process.platform === "win32" ? "npx.cmd" : "npx";

function run(args) {
  const result = spawnSync(executable, args, { cwd: root, stdio: "inherit", shell: process.platform === "win32" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status || 1);
}

if (!existsSync(target)) {
  console.log("Building the shared React interface for native webviews...");
  const npm = process.platform === "win32" ? "npm.cmd" : "npm";
  const build = spawnSync(npm, ["run", "build:native"], { cwd: root, stdio: "inherit", shell: process.platform === "win32" });
  if (build.error) throw build.error;
  if (build.status !== 0) process.exit(build.status || 1);
  console.log(`Adding Capacitor ${platform} platform...`);
  run(["cap", "add", platform]);
} else {
  console.log(`${platform} project already exists; preserving its native settings.`);
}

if (platform === "android") {
  const appRoot = resolve(root, "android/app/src/main");
  const manifestPath = resolve(appRoot, "AndroidManifest.xml");
  if (!existsSync(manifestPath)) throw new Error("AndroidManifest.xml was not generated by Capacitor.");

  const drawable = resolve(appRoot, "res/drawable");
  mkdirSync(drawable, { recursive: true });
  cpSync(resolve(root, "native/android/res"), resolve(appRoot, "res"), { recursive: true, force: true });
  copyFileSync(resolve(root, "native/android/ic_stat_nawa.png"), resolve(drawable, "ic_stat_nawa.png"));

  let manifest = readFileSync(manifestPath, "utf8");
  const permissions = [
    "android.permission.POST_NOTIFICATIONS",
    "android.permission.SCHEDULE_EXACT_ALARM",
  ];
  for (const permission of permissions) {
    if (!manifest.includes(`android:name="${permission}"`)) {
      manifest = manifest.replace(/(<manifest[^>]*>)/, `$1\n    <uses-permission android:name="${permission}" />`);
    }
  }
  const applicationTag = manifest.match(/<application\b[^>]*>/);
  if (applicationTag) {
    let appTag = applicationTag[0];
    if (/android:icon="[^"]*"/.test(appTag)) appTag = appTag.replace(/android:icon="[^"]*"/, 'android:icon="@mipmap/ic_launcher"');
    else appTag = appTag.replace(/>$/, ' android:icon="@mipmap/ic_launcher">');
    if (/android:roundIcon="[^"]*"/.test(appTag)) appTag = appTag.replace(/android:roundIcon="[^"]*"/, 'android:roundIcon="@mipmap/ic_launcher_round"');
    else appTag = appTag.replace(/>$/, ' android:roundIcon="@mipmap/ic_launcher_round">');
    manifest = manifest.replace(applicationTag[0], appTag);
  }
  writeFileSync(manifestPath, manifest);

  // Keep the generated Capacitor app icon when upgrading an existing Android project.
  const stringsPath = resolve(appRoot, "res/values/strings.xml");
  if (existsSync(stringsPath)) {
    const strings = readFileSync(stringsPath, "utf8").replace(/(<string name="app_name">)[^<]*(<\/string>)/, "$1نَواة$2");
    writeFileSync(stringsPath, strings);
  }

  console.log("Android notification permissions and Nawa small-notification icon are configured.");
}

console.log(`Capacitor ${platform} setup is ready. Next run: npm run mobile:sync`);
